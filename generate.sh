#!/usr/bin/env bash
# USPS REST v3 multi-API codegen (UPS-style).
# Default source: committed specs/ (portal OpenAPI + focused Domestic Prices).
# Override: SPEC_DIR=/path/to/yamls make generate
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

OAPI_CODEGEN_VERSION="${OAPI_CODEGEN_VERSION:-v2.5.0}"
export PATH="$(go env GOPATH)/bin:${PATH}"

if ! command -v oapi-codegen >/dev/null 2>&1; then
  echo "installing oapi-codegen@${OAPI_CODEGEN_VERSION} ..."
  go install "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@${OAPI_CODEGEN_VERSION}"
fi

if ! command -v python3 >/dev/null 2>&1; then
  echo "python3 required" >&2
  exit 1
fi
python3 -c "import yaml" 2>/dev/null || {
  echo "PyYAML required: pip3 install pyyaml" >&2
  exit 1
}

MANIFEST="${ROOT}/scripts/manifest.yaml"
PREPROCESS="${ROOT}/scripts/preprocess.py"
SPEC_CACHE="${ROOT}/.cache/specs"
OUT_ROOT="${ROOT}/internal/generated"
# Committed portal / focused specs
DEFAULT_SPEC_DIR="${ROOT}/specs"
SPEC_DIR="${SPEC_DIR:-$DEFAULT_SPEC_DIR}"
TMPDIR="$(mktemp -d "${TMPDIR:-/tmp}/usps-sdk-gen.XXXXXX")"
trap 'rm -rf "$TMPDIR"' EXIT

mkdir -p "$SPEC_CACHE" "$OUT_ROOT"

# Emit ServerURL lookup into the public usps package (per-API path-qualified bases).
python3 - "$MANIFEST" "${ROOT}/usps/servers.gen.go" <<'PY'
import sys, yaml
manifest, out_path = sys.argv[1], sys.argv[2]
doc = yaml.safe_load(open(manifest, encoding="utf-8"))
default_tem = doc.get("server_tem", "https://apis-tem.usps.com").rstrip("/")
default_prod = doc.get("server_prod", "https://apis.usps.com").rstrip("/")
lines = [
    "// Code generated by generate.sh from scripts/manifest.yaml. DO NOT EDIT.",
    "package usps",
    "",
    "type apiServer struct{ TEM, Prod string }",
    "",
    "var apiServers = map[string]apiServer{",
]
for a in doc["apis"]:
    pkg = a["package"]
    tem = str(a.get("server_tem") or default_tem).rstrip("/")
    prod = str(a.get("server_prod") or default_prod).rstrip("/")
    lines.append(f'\t"{pkg}": {{TEM: "{tem}", Prod: "{prod}"}},')
lines += [
    "}",
    "",
    "// ServerURL returns the USPS API base URL for a package and environment.",
    '// env is "production" or anything else (tem/sandbox).',
    "func ServerURL(env, apiPackage string) string {",
    "\ts, ok := apiServers[apiPackage]",
    "\tif !ok {",
    "\t\treturn BaseURL(env)",
    "\t}",
    '\tif env == "production" {',
    "\t\treturn s.Prod",
    "\t}",
    "\treturn s.TEM",
    "}",
    "",
]
open(out_path, "w", encoding="utf-8").write("\n".join(lines))
print(f"→ wrote {out_path}")
PY

ENTRIES_FILE="${TMPDIR}/entries.txt"
python3 - "$MANIFEST" <<'PY' >"$ENTRIES_FILE"
import sys, yaml
doc = yaml.safe_load(open(sys.argv[1], encoding="utf-8"))
default_tem = doc.get("server_tem", "https://apis-tem.usps.com")
default_prod = doc.get("server_prod", "https://apis.usps.com")
for a in doc["apis"]:
    globs = ",".join(a.get("portal_globs") or [])
    tem = a.get("server_tem") or default_tem
    prod = a.get("server_prod") or default_prod
    print("|".join([a["package"], a["file"], a["id"], tem, prod, globs]))
PY

resolve_spec() {
  local pkg="$1" file="$2" globs_csv="$3"
  local cached="${SPEC_CACHE}/${file}"

  # 1) SPEC_DIR (defaults to ./specs)
  if [[ -n "${SPEC_DIR:-}" && -d "${SPEC_DIR}" ]]; then
    if [[ -f "${SPEC_DIR}/${file}" ]]; then
      echo "· specs ${pkg} ← ${file}"
      cp "${SPEC_DIR}/${file}" "$cached"
      return 0
    fi
    local found=""
    local IFS=','
    for pat in $globs_csv; do
      [[ -z "$pat" ]] && continue
      local hit
      hit=$(python3 - "$SPEC_DIR" "$pat" <<'PY'
import sys
from pathlib import Path
root, pat = Path(sys.argv[1]), sys.argv[2]
hits = sorted(root.glob(pat))
if hits:
    print(hits[0])
PY
)
      if [[ -n "$hit" ]]; then
        found="$hit"
        break
      fi
    done
    if [[ -n "$found" ]]; then
      echo "· portal ${pkg} ← $(basename "$found")"
      cp "$found" "$cached"
      return 0
    fi
  fi

  # 2) SPEC_LOCAL_DIR exact filename
  if [[ -n "${SPEC_LOCAL_DIR:-}" && -f "${SPEC_LOCAL_DIR}/${file}" ]]; then
    echo "· local ${file}"
    cp "${SPEC_LOCAL_DIR}/${file}" "$cached"
    return 0
  fi

  # 3) cache hit
  if [[ -f "$cached" && "${FORCE_FETCH:-}" != "1" ]]; then
    echo "· cache hit ${file}"
    return 0
  fi

  cat >&2 <<MSG
missing OpenAPI for ${pkg} (${file}).

Expected under specs/ (or SPEC_DIR / SPEC_LOCAL_DIR).
MSG
  return 1
}

fail=0
while IFS='|' read -r pkg file id server_tem server_prod globs_csv; do
  [[ -z "${pkg:-}" ]] && continue
  if ! resolve_spec "$pkg" "$file" "$globs_csv"; then
    fail=1
    continue
  fi
  cached="${SPEC_CACHE}/${file}"
  cleaned="${TMPDIR}/${pkg}.yml"
  out_dir="${OUT_ROOT}/${pkg}"
  mkdir -p "$out_dir"
  echo "→ generate ${pkg} (${id})"
  if ! python3 "$PREPROCESS" \
      --in "$cached" \
      --out "$cleaned" \
      --server-tem "$server_tem" \
      --server-prod "$server_prod"; then
    echo "preprocess failed: ${id}" >&2
    fail=1
    continue
  fi
  size=$(wc -c <"$cleaned" | tr -d ' ')
  if [[ "$size" -gt 800000 ]]; then
    oapi-codegen -generate types -package "$pkg" -o "${out_dir}/types.gen.go" "$cleaned" || { fail=1; continue; }
    oapi-codegen -generate client -package "$pkg" -o "${out_dir}/client.gen.go" "$cleaned" || { fail=1; continue; }
  else
    rm -f "${out_dir}/types.gen.go"
    oapi-codegen -generate types,client -package "$pkg" -o "${out_dir}/client.gen.go" "$cleaned" || { fail=1; continue; }
  fi
  if command -v gofmt >/dev/null 2>&1; then
    gofmt -w "${out_dir}"/*.go
  fi
done <"$ENTRIES_FILE"

if [[ "$fail" -ne 0 ]]; then
  echo "generate finished with errors" >&2
  exit 1
fi
echo "generate done."
